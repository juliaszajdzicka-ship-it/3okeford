// Regenerates the hero image sizes in public/ from the full-resolution original.
//
// Nothing in this folder is served or bundled. It exists so the hero can be
// re-cut later without hunting for the original photo.
//
// Run it from the repo root:
//   npm install --no-save sharp
//   node assets-source/generate-hero.mjs

import sharp from 'sharp'
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const here = path.dirname(fileURLToPath(import.meta.url))
const SRC = path.join(here, 'hambledon-hill.jpeg')
const PUBLIC = path.join(here, '..', 'public')
const SRC_DIR = path.join(here, '..', 'src')

const widths = [2400, 1600, 900]

for (const width of widths) {
  const out = path.join(PUBLIC, `hero-${width}.jpg`)
  await sharp(SRC).resize({ width }).jpeg({ quality: 78, mozjpeg: true }).toFile(out)
  console.log(`${String(Math.round(fs.statSync(out).size / 1024)).padStart(5)} KB  hero-${width}.jpg`)
}

// Tiny blurred stand-in, inlined as a data URI so it needs no extra request.
const tiny = await sharp(SRC).resize({ width: 24 }).jpeg({ quality: 40 }).toBuffer()
fs.writeFileSync(
  path.join(SRC_DIR, 'heroBlur.js'),
  `// Generated by assets-source/generate-hero.mjs. Do not edit by hand.\n` +
    `export const HERO_BLUR = 'data:image/jpeg;base64,${tiny.toString('base64')}'\n`,
)
console.log(`${String(Math.round(tiny.length / 1024)).padStart(5)} KB  src/heroBlur.js (inlined)`)
